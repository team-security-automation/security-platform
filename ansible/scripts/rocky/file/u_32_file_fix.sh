#!/bin/bash
# ============================================================
# U-32 (중) 홈 디렉토리로 지정한 디렉토리의 존재 관리 - 조치 스크립트
# 분류: 파일 및 디렉터리 관리 | 대상: Rocky Linux (rocky)
# 주의: 설정 파일을 변경하는 경우 원본을 .bak_<시각> 으로 백업합니다.
#       운영 서버 적용 전 반드시 테스트 서버에서 먼저 검증하세요.
# 실행: sudo bash u_32_file_fix.sh
# ============================================================

# JSON 이스케이프 유틸 (따옴표/개행 처리)
json_esc() {
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    s="$(printf '%s' "$s" | tr '\n' ' ')"
    printf '%s' "$s"
}

# ============================================================
# 1. 기본 정보
# ============================================================
FIX_ID="U-32"
CATEGORY="파일 및 디렉터리 관리"
RISK_LEVEL="중"

# ============================================================
# 2~4. 현재 상태 확인 후 필요 시 조치 실행
#   STATUS 값: 조치완료 | 조치불필요 | 조치실패 | 수동조치필요
# ============================================================
FIXED=0
while IFS=: read -r uname _ uid gid _ home shell; do
    [ "$uid" -lt 1000 ] && [ "$uname" != "root" ] && continue
    echo "$shell" | grep -qE '(nologin|false)$' && continue
    if [ -n "$home" ] && [ ! -d "$home" ]; then
        mkdir -p "$home" 2>/dev/null
        chown "$uname":"$gid" "$home" 2>/dev/null
        chmod 700 "$home" 2>/dev/null
        FIXED=$((FIXED + 1))
    fi
done < /etc/passwd

if [ $FIXED -gt 0 ]; then
    STATUS="조치완료"; ACTION="${FIXED}개 계정에 대해 누락된 홈 디렉터리를 생성함(소유자:해당 계정, 권한:700). 계정 자체의 존속 필요 여부는 별도 검토 필요"
else
    STATUS="조치불필요"; ACTION="홈 디렉터리가 없는 계정이 없음"
fi

# ============================================================
# 5. JSON 출력
# ============================================================
cat <<EOF
{
  "fix_id": "$(json_esc "$FIX_ID")",
  "category": "$(json_esc "$CATEGORY")",
  "status": "$(json_esc "$STATUS")",
  "action": "$(json_esc "$ACTION")",
  "hostname": "$(hostname)",
  "risk_level": "$(json_esc "$RISK_LEVEL")"
}
EOF

# ============================================================
# 6. 정상 종료
# ============================================================
exit 0
