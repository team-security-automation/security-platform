#!/bin/bash
# ============================================================
# U-31 (중) 홈 디렉토리 소유자 및 권한 설정 - 조치 스크립트
# 분류: 파일 및 디렉터리 관리 | 대상: Rocky Linux (rocky)
# 주의: 설정 파일을 변경하는 경우 원본을 .bak_<시각> 으로 백업합니다.
#       운영 서버 적용 전 반드시 테스트 서버에서 먼저 검증하세요.
# 실행: sudo bash u_31_file_fix.sh
# ============================================================

# JSON 이스케이프 유틸 (따옴표/개행 처리)
json_esc() {
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    s="$(printf '%s' "$s" | tr '\n' ' ')"
    printf '%s' "$s"
}

# ============================================================
# 1. 기본 정보
# ============================================================
FIX_ID="U-31"
CATEGORY="파일 및 디렉터리 관리"
RISK_LEVEL="중"

# ============================================================
# 2~4. 현재 상태 확인 후 필요 시 조치 실행
#   STATUS 값: 조치완료 | 조치불필요 | 조치실패 | 수동조치필요
# ============================================================
FIXED=0
while IFS=: read -r uname _ uid _ _ home shell; do
    [ "$uid" -lt 1000 ] && [ "$uname" != "root" ] && continue
    [ -d "$home" ] || continue
    OWNER=$(stat -c '%U' "$home" 2>/dev/null)
    PERM=$(stat -c '%a' "$home" 2>/dev/null)
    OTHER_W=$(( (10#$PERM) % 10 ))
    if [ "$OWNER" != "$uname" ] || [ $(( OTHER_W & 2 )) -ne 0 ]; then
        chown "$uname" "$home" 2>/dev/null
        chmod o-w "$home" 2>/dev/null
        FIXED=$((FIXED + 1))
    fi
done < /etc/passwd

if [ $FIXED -gt 0 ]; then
    STATUS="조치완료"; ACTION="${FIXED}개 홈 디렉터리의 소유자를 해당 계정으로, 타 사용자 쓰기 권한을 제거함"
else
    STATUS="조치불필요"; ACTION="이미 모든 홈 디렉터리가 기준을 충족함"
fi

# ============================================================
# 5. JSON 출력
# ============================================================
cat <<EOF
{
  "fix_id": "$(json_esc "$FIX_ID")",
  "category": "$(json_esc "$CATEGORY")",
  "status": "$(json_esc "$STATUS")",
  "action": "$(json_esc "$ACTION")",
  "hostname": "$(hostname)",
  "risk_level": "$(json_esc "$RISK_LEVEL")"
}
EOF

# ============================================================
# 6. 정상 종료
# ============================================================
exit 0
